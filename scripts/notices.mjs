// Writes THIRD-PARTY-NOTICES.md, which every build runs first and ships (it's gitignored, never committed): MIT/ISC/BSD-2-Clause all require the licence notice to travel with the code.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUTPUT = join(ROOT, "THIRD-PARTY-NOTICES.md");
const LICENCE_FILES = [
  "LICENSE",
  "LICENSE.md",
  "LICENSE.txt",
  "LICENCE",
  "LICENCE.md",
];

const lock = JSON.parse(readFileSync(join(ROOT, "package-lock.json"), "utf8"));
if (lock.lockfileVersion < 3) {
  throw new Error(
    `package-lock.json is version ${lock.lockfileVersion}; this script needs 3 or newer.`,
  );
}

// The lockfile is input, not truth: a key that isn't a plain package name refuses the whole document rather than becoming a filesystem path.
const PACKAGE_NAME = /^(?:@[a-z0-9][\w.-]*\/)?[a-z0-9][\w.-]*$/i;

// No runtime npm dependencies exist (all devDependencies), so the lockfile scan yields zero packages — Lucide (hand-copied) and Workbox (inlined into the SW) are cited here by hand instead.
const BUNDLED = [
  {
    name: "Lucide",
    version: "1.41.0",
    licence: "ISC",
    from: "licenses/lucide-ISC.txt",
    what:
      "The `ICONS` table in src/main.js and the artwork in src/icons/ (icon.svg, " +
      "icon-maskable.svg, favicon-light.svg, favicon-dark.svg and the four PNGs " +
      "rendered from the first two) redistribute SVG path data copied by hand from " +
      "lucide-static 1.41.0 (https://lucide.dev), not installed as a dependency.",
  },
  {
    name: "Lucide (Feather-derived glyphs)",
    version: "1.41.0",
    licence: "MIT",
    from: "licenses/lucide-feather-MIT.txt",
    what:
      "Some of the glyphs redistributed above are Feather-derived and carry this " +
      "additional grant alongside Lucide's own " +
      "(https://github.com/lucide-icons/lucide/blob/main/LICENSE).",
  },
  {
    name: "Workbox",
    version: JSON.parse(
      readFileSync(
        join(ROOT, "node_modules/workbox-core/package.json"),
        "utf8",
      ),
    ).version,
    licence: "MIT",
    from: "node_modules/workbox-core/LICENSE",
    what:
      "The Workbox runtime is inlined into dist/sw.js by workbox-build. It is a " +
      "development dependency of this project, but its code is served to every visitor.",
  },
];

const read = (path) => {
  const text = readFileSync(path, "utf8").replace(/\r\n?/gu, "\n").trim();
  if (text.includes("```")) {
    throw new Error(
      `${path} contains a code fence and cannot be quoted as one`,
    );
  }
  return text;
};

const packages = Object.entries(lock.packages)
  .filter(([path, node]) => path && !node.dev)
  .map(([path, node]) => {
    const name = path.replace(/^.*node_modules\//u, "");
    if (!PACKAGE_NAME.test(name)) {
      throw new Error(
        `package-lock.json entry "${path}" is not a plain npm package name.`,
      );
    }
    return { name, ...node };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const sections = packages.map(({ name, version, license }) => {
  const path = LICENCE_FILES.map((file) =>
    join(ROOT, "node_modules", name, file),
  ).find(existsSync);
  const text = path
    ? read(path)
    : `This package publishes no licence file. Declared licence: ${license}.`;
  return `## ${name} ${version} — ${license}\n\n\`\`\`\n${text}\n\`\`\`\n`;
});

const bundled = BUNDLED.map(
  ({ name, version, licence, from, what }) =>
    `## ${name} ${version} — ${licence}\n\n${what}\n\n\`\`\`\n${read(join(ROOT, from))}\n\`\`\`\n`,
);

const output = `# Third-party notices

This application bundles the open source software listed below. Their licence texts are
reproduced in full, as those licences require.

Generated by \`scripts/notices.mjs\` when the app is built.

${[...sections, ...bundled].join("\n")}`;

const summary = `${packages.length} packages${BUNDLED.length ? ` and ${BUNDLED.length} bundled work(s)` : ""}`;

writeFileSync(OUTPUT, output);
console.log(`${OUTPUT}: ${summary}`);
